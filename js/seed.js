function extraParagraphs() {
  const out = [];
  for (let i = 0; i < 60; i++) {
    const opener = EXTRA_OPENERS[i % EXTRA_OPENERS.length];
    const a = EXTRA_IDEAS[i % EXTRA_IDEAS.length];
    const b = EXTRA_IDEAS[(i * 7 + 3) % EXTRA_IDEAS.length];
    out.push(opener + a + b);
  }
  return out;
}

export function buildSeedOps(doc) {
  const ops = [];
  let lastId = -1;
  const paragraphs = PARAGRAPHS.concat(extraParagraphs());
  for (let i = 0; i < paragraphs.length; i++) {
    const text = paragraphs[i] + (i === paragraphs.length - 1 ? '' : '\n\n');
    const op = doc.createInsert(lastId, text, Date.now() + i);
    op.vclock = {}; // 播种操作无因果依赖，任何副本都可立即应用
    ops.push(op);
    doc.apply(op);
    const len = Array.from(text).length;
    lastId = `${String(op.lamp).padStart(12, '0')}.${op.site}.${String(op.seq).padStart(8, '0')}.${String(len - 1).padStart(5, '0')}`;
  }
  return ops;
}

export function seedTextLength() {
  return PARAGRAPHS.reduce((n, p, i) => n + Array.from(p).length + (i === PARAGRAPHS.length - 1 ? 0 : 2), 0);
}
